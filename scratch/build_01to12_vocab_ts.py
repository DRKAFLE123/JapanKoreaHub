def extract_kanji_array(word):
    chars = re.findall(r'[\u4e00-\u9faf]', word)
    return list(dict.fromkeys(chars))

def get_pos(kana, kanji, eng):
    eng_lower = eng.lower()
    if kana.endswith('ます') or kana.endswith('する') or 'verb' in eng_lower:
        return 'Verb'
    elif (kana.endswith('い') or kanji.endswith('い')) and not kana.endswith('ない') and 'adjective' not in eng_lower:
        return 'I-Adj'
    elif kana.endswith('[な]') or kanji.endswith('[な]') or 'na-adj' in eng_lower:
        return 'Na-Adj'
    return 'Noun'

def get_nepali(kana, kanji, eng):
    if kanji in nepali_dict:
        return nepali_dict[kanji]
    if kana in nepali_dict:
        return nepali_dict[kana]
    # Check partial
    for k, v in nepali_dict.items():
        if k == kana or k == kanji:
            return v
    return eng

