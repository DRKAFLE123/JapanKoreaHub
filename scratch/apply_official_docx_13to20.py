def get_np_vocab(jp, eng):
    jp_clean = jp.strip()
    if jp_clean in nepali_vocab_map:
        return nepali_vocab_map[jp_clean]
    for k, v in nepali_vocab_map.items():
        if k in jp_clean:
            return v
    return f"{eng} (नेपाली)"

