// Sort dictionary by length descending to match longest phrases first
const SORTED_DICT = [...KANJI_FURIGANA_DICT].sort((a, b) => b[0].length - a[0].length);

// Regex to test if a string contains Kanji characters
const KANJI_REGEX = /[\u4e00-\u9faf\u3400-\u4dbf]/;
// Explicit bracket format `[kanji|furigana]`
const BRACKET_PATTERN = /\[([^\|\]]+)\|([^\]]+)\]/g;

/**
 * FuriganaText
 * Renders Japanese text with native HTML <ruby><rt>furigana</rt></ruby> directly above Kanji characters.
 * - Katakana loanwords (ポリッシャー, エクストラクター, スクイジー, etc.) remain untouched.
 * - Supports explicit `[漢字|かんじ]` brackets.
 * - Automatically provides furigana above unbracketed Kanji using the comprehensive building cleaning dictionary.
 * - When showFurigana is false, the text cleanly renders without ruby furigana.
 */
export default function FuriganaText({ text, showFurigana = true, className = '' }: Props) {
  const renderedContent = useMemo(() => {
    if (!text) return null;

    // Step 1: Pre-process text to resolve explicit bracket syntax `[漢字|かんじ]`
    let segments: { isRuby: boolean; kanji: string; furigana?: string }[] = [];
    let lastIndex = 0;
    let match: RegExpExecArray | null;
    BRACKET_PATTERN.lastIndex = 0;

    while ((match = BRACKET_PATTERN.exec(text)) !== null) {
      const [fullMatch, kanji, furigana] = match;
      const start = match.index;

      if (start > lastIndex) {
        segments.push({ isRuby: false, kanji: text.substring(lastIndex, start) });
      }

      segments.push({ isRuby: true, kanji, furigana });
      lastIndex = start + fullMatch.length;
    }

    if (lastIndex < text.length) {
      segments.push({ isRuby: false, kanji: text.substring(lastIndex) });
    }

    // If there were no brackets, segments has 1 item with isRuby: false
    if (segments.length === 0) {
      segments.push({ isRuby: false, kanji: text });
    }

    // Step 2: For non-bracket segments, if showFurigana is true, apply dictionary lookup for Kanji
    const elements: React.ReactNode[] = [];
    let keyCounter = 0;

    segments.forEach((seg) => {
      if (seg.isRuby) {
        // Explicit ruby item
        if (showFurigana && seg.furigana) {
          elements.push(
            <ruby key={`exp-${keyCounter++}`} className="inline-ruby align-baseline mx-[0.5px]">
              {seg.kanji}
              <rt className="text-[10px] sm:text-[11px] font-semibold text-emerald-700 select-none leading-none -top-1">
                {seg.furigana}
              </rt>
            </ruby>
          );
        } else {
          elements.push(<span key={`exp-${keyCounter++}`}>{seg.kanji}</span>);
        }
        return;
      }

      const str = seg.kanji;
      // If no furigana needed or no Kanji present (e.g. pure Katakana or Hiragana or English), output directly
      if (!showFurigana || !KANJI_REGEX.test(str)) {
        elements.push(<span key={`txt-${keyCounter++}`}>{str}</span>);
        return;
      }

      // Dictionary matching algorithm: tokenize string matching known kanji terms
      let cur = 0;
      while (cur < str.length) {
        // Check if current position starts with a dictionary term
        let matched = false;
        for (let i = 0; i < SORTED_DICT.length; i++) {
          const [dictKanji, dictFurigana] = SORTED_DICT[i];
          if (str.startsWith(dictKanji, cur)) {
            elements.push(
              <ruby key={`auto-${keyCounter++}`} className="inline-ruby align-baseline mx-[0.5px]">
                {dictKanji}
                <rt className="text-[10px] sm:text-[11px] font-semibold text-emerald-700 select-none leading-none -top-1">
                  {dictFurigana}
                </rt>
              </ruby>
            );
            cur += dictKanji.length;
            matched = true;
            break;
          }
        }

        if (!matched) {
          // Check if char is not Kanji (e.g. Katakana, Hiragana, symbol, ASCII)
          let end = cur + 1;
          // Consume non-kanji characters together
          if (!KANJI_REGEX.test(str[cur])) {
            while (end < str.length && !KANJI_REGEX.test(str[end])) {
              end++;
            }
          }
          elements.push(<span key={`chunk-${keyCounter++}`}>{str.substring(cur, end)}</span>);
          cur = end;
        }
      }
    });

    return elements;
  }, [text, showFurigana]);

  return <span className={className}>{renderedContent}</span>;
}

