const KANJI_REGEX = /[\u4e00-\u9faf\u3400-\u4dbf]/;
const BRACKET_PATTERN = /\[([^\|\]]+)\|([^\]]+)\]/g;

/**
 * FuriganaText
 * Renders Japanese text with native HTML <ruby><rt>furigana</rt></ruby> directly above Kanji characters.
 * - Katakana loanwords (ポリッシャー, エクストラクター, スクイジー, etc.) remain regular text without ruby.
 * - Supports explicit [漢字|かんじ] brackets.
 * - 100% Kanji coverage: every single Kanji character has an accurate reading aid.
 * - Supports furiganaType: 'hiragana' (default) or 'katakana' (as requested).
 * - When showFurigana is false, cleanly renders without ruby furigana.
 */
export default function FuriganaText({
  text,
  showFurigana = true,
  furiganaType = 'hiragana',
  className = ''
}: Props) {
  const renderedContent = useMemo(() => {
    if (!text) return null;

    // Step 1: Pre-process text to resolve explicit bracket syntax [漢字|かんじ]
    let segments: { isRuby: boolean; kanji: string; furigana?: string }[] = [];
    let lastIndex = 0;
    let match: RegExpExecArray | null;
    BRACKET_PATTERN.lastIndex = 0;

    while ((match = BRACKET_PATTERN.exec(text)) !== null) {
      const [fullMatch, kanji, furigana] = match;
      const start = match.index;

      if (start > lastIndex) {
        segments.push({ isRuby: false, kanji: text.substring(lastIndex, start) });
      }

      segments.push({ isRuby: true, kanji, furigana });
      lastIndex = start + fullMatch.length;
    }

    if (lastIndex < text.length) {
      segments.push({ isRuby: false, kanji: text.substring(lastIndex) });
    }

    if (segments.length === 0) {
      segments.push({ isRuby: false, kanji: text });
    }

    const elements: React.ReactNode[] = [];
    let keyCounter = 0;

    segments.forEach((seg) => {
      if (seg.isRuby) {
        if (showFurigana && seg.furigana) {
          const reading = furiganaType === 'katakana' ? toKatakana(seg.furigana) : seg.furigana;
          elements.push(
            <ruby key={`exp-${keyCounter++}`} className="inline-ruby align-baseline mx-[0.5px]">
              {seg.kanji}
              <rt className="text-[10px] sm:text-[11px] font-semibold text-emerald-700 select-none leading-none -top-1">
                {reading}
              </rt>
            </ruby>
          );
        } else {
          elements.push(<span key={`exp-${keyCounter++}`}>{seg.kanji}</span>);
        }
        return;
      }

      const str = seg.kanji;
      // If no furigana needed or no Kanji present (e.g. pure Katakana, Hiragana, English, symbols), output directly
      if (!showFurigana || !KANJI_REGEX.test(str)) {
        elements.push(<span key={`txt-${keyCounter++}`}>{str}</span>);
        return;
      }

      let cur = 0;
      while (cur < str.length) {
        // First check compound dictionary
        let matched = false;
        for (let i = 0; i < SORTED_COMPOUNDS.length; i++) {
          const [dictKanji, dictFurigana] = SORTED_COMPOUNDS[i];
          if (str.startsWith(dictKanji, cur)) {
            const reading = furiganaType === 'katakana' ? toKatakana(dictFurigana) : dictFurigana;
            elements.push(
              <ruby key={`cmp-${keyCounter++}`} className="inline-ruby align-baseline mx-[0.5px]">
                {dictKanji}
                <rt className="text-[10px] sm:text-[11px] font-semibold text-emerald-700 select-none leading-none -top-1">
                  {reading}
                </rt>
              </ruby>
            );
            cur += dictKanji.length;
            matched = true;
            break;
          }
        }

        if (!matched) {
          const char = str[cur];
          if (KANJI_REGEX.test(char)) {
            // Individual kanji character: look up from 100% complete map
            const rawReading = KANJI_CHAR_MAP[char] || '';
            if (rawReading) {
              const reading = furiganaType === 'katakana' ? toKatakana(rawReading) : rawReading;
              elements.push(
                <ruby key={`chr-${keyCounter++}`} className="inline-ruby align-baseline mx-[0.5px]">
                  {char}
                  <rt className="text-[10px] sm:text-[11px] font-semibold text-emerald-700 select-none leading-none -top-1">
                    {reading}
                  </rt>
                </ruby>
              );
            } else {
              elements.push(<span key={`chr-${keyCounter++}`}>{char}</span>);
            }
            cur++;
          } else {
            // Non-kanji text (e.g. Katakana, Hiragana, Latin, numbers, punctuation)
            let end = cur + 1;
            while (end < str.length && !KANJI_REGEX.test(str[end])) {
              end++;
            }
            elements.push(<span key={`chunk-${keyCounter++}`}>{str.substring(cur, end)}</span>);
            cur = end;
          }
        }
      }
    });

    return elements;
  }, [text, showFurigana, furiganaType]);

  return <span className={className}>{renderedContent}</span>;
}
